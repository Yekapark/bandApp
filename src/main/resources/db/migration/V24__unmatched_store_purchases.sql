-- 돈은 들어왔는데 PREMIUM 을 줄 밴드를 못 찾은 스토어 구독(QA BILL-31).
--
-- 만료 뒤 Play 스토어 「다시 구독」 은 구매에 밴드 표시가 없고 이전 구독 토큰(linkedPurchaseToken)만 따라온다. 서버가 그
-- 토큰으로 원래 밴드를 못 찾으면 아무 밴드도 올리지 않고 포기한다. 예전에는 로그 한 줄만 남아, 배포로 컨테이너가
-- 바뀌면 사라지고 매일 점검은 24시간만 봐서 하루 지나면 경보가 저절로 꺼졌다. 해결할 때까지 남도록 테이블에 둔다.
--
-- 행은 해결(resolved_at)될 때까지 매일 점검(deploy/prod-check.sh)을 실패시킨다. 해결은 대부분 서버가 한다
-- (StoreSubscriptionService.resolveUnmatchedPurchases): 그 토큰이 어떤 경로로든 밴드에 붙었거나, 스토어에서 끝났거나
-- (확인 처리를 못 받아 3일 뒤 자동 환불 포함), 운영자가 target_band_id 를 정했으면 그 밴드에 반영한다.
-- 운영자 명령은 tools/purchases.py.

CREATE TABLE unmatched_store_purchases (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store                 VARCHAR(20)  NOT NULL,
    purchase_token        TEXT         NOT NULL,
    notification_type     INTEGER,
    product_id            VARCHAR(100),
    order_id              VARCHAR(100),
    linked_purchase_token TEXT,
    received_at           TIMESTAMPTZ  NOT NULL,
    target_band_id        BIGINT,
    resolved_at           TIMESTAMPTZ,
    resolution            VARCHAR(200),

    CONSTRAINT ck_unmatched_store_purchases_store CHECK (store IN ('GOOGLE_PLAY')),
    CONSTRAINT ux_unmatched_store_purchases_token UNIQUE (purchase_token)
);

CREATE INDEX ix_unmatched_store_purchases_open ON unmatched_store_purchases (received_at)
    WHERE resolved_at IS NULL;

COMMENT ON TABLE unmatched_store_purchases IS
    '돈은 들어왔는데 밴드를 못 찾은 스토어 구독. resolved_at NULL = 미해결(매일 점검 실패).';
COMMENT ON COLUMN unmatched_store_purchases.target_band_id IS
    '운영자가 정한 반영 대상 밴드(tools/purchases.py link). 서버 배치가 이 밴드에 PREMIUM·확인 처리 후 해결한다.';
COMMENT ON COLUMN unmatched_store_purchases.resolution IS
    '어떻게 끝났는지 — 자동 연결·스토어에서 끝남(자동 환불 등)·운영자 연결·운영자 메모.';
